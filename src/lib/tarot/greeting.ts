import type { ToneKey } from "./tone";

/** 방을 처음 열었을 때(아직 리딩이 하나도 없을 때) 캐릭터가 먼저 건네는 인사말 — LLM 호출 없이
 * 톤별로 고정된 템플릿을 쓴다(차감 대상도 아니고, 매번 똑같은 4가지 요소만 담으면 되는
 * 정형화된 문장이라 LLM 호출 비용·지연·톤 이탈 위험을 감수할 이유가 없음). 닉네임에 받침
 * 유무에 따라 달라지는 호격조사(아/야, 이/가)는 붙이지 않는 문장 구조로 설계해서, 어떤 닉네임을
 * 쓰더라도 어색해지지 않도록 한다.
 *
 * 배열의 각 원소는 별도의 말풍선 하나에 대응한다(2026-09-16, 한 말풍선에 다 몰아넣지 말고
 * 나눠달라는 요청) — 항상 [인사 뉘앙스, 캐릭터 이름 소개, 캐릭터 스타일 소개, 질문 유도] 4개. */
export function buildGreeting(tone: ToneKey, nickname: string): string[] {
  switch (tone) {
    case "warm":
      return [
        "안녕하세요!",
        "저는 루미예요.",
        "밝고 순수한 마음으로 당신의 이야기를 들어드릴게요.",
        `${nickname}님, 오늘은 어떤 게 궁금하신가요? 마음에 걸리는 일이 있다면 편하게 말씀해주세요.`,
      ];
    case "direct":
      return [
        "왔구나.",
        "나는 그레모라야.",
        "인생 좀 살아본 할머니답게, 돌려 말하지 않고 핵심만 딱 짚어줄게.",
        `요즘 뭐가 그렇게 마음을 힘들게 해, ${nickname}? 편하게 말해봐.`,
      ];
    case "mystical":
      return [
        "어서 오세요.",
        "저는 셀레네아입니다.",
        "조용히 카드의 목소리를 전해드리는 사람이에요.",
        `${nickname}님, 지금 마음속에 어떤 물음이 맴돌고 있나요? 천천히 들려주세요.`,
      ];
    case "friendly":
      return [
        "왔어?",
        "나 모리야.",
        "편하게 친구처럼 얘기 나누는 거 좋아해.",
        `요즘 뭐가 궁금하거나 힘든 거 있어, ${nickname}? 나한테 편하게 말해봐.`,
      ];
  }
}
